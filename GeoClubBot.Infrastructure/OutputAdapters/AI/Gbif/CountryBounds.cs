namespace Infrastructure.OutputAdapters.AI.Gbif;

/// <summary>A rectangle of the map in degrees: west and south, east and north.</summary>
internal readonly record struct MapBounds(double West, double South, double East, double North)
{
    public double Width => East - West;

    public double Height => North - South;

    /// <summary>The smallest rectangle holding both.</summary>
    public MapBounds Union(MapBounds other) =>
        new(Math.Min(West, other.West), Math.Min(South, other.South), Math.Max(East, other.East), Math.Max(North, other.North));
}

